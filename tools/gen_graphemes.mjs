#!/usr/bin/env node
// SPDX-License-Identifier: AGPL-3.0-only
// Generate src/zymbol/graphemes.js — the extended grapheme clusters of UAX #29
// for the two browser engines (`std/text`'s `graphemes`, D-19; and the clusters
// `std/term` measures) — from the Unicode Character Database.
//
//   node tools/gen_graphemes.mjs <ucd-dir>           # write src/zymbol/graphemes.js
//   node tools/gen_graphemes.mjs <ucd-dir> --check   # exit 1 if it is not current
//   node tools/gen_graphemes.mjs <ucd-dir> --test    # run GraphemeBreakTest.txt on it
//
// <ucd-dir> holds GraphemeBreakProperty.txt, emoji-data.txt,
// DerivedCoreProperties.txt and GraphemeBreakTest.txt of one version, from
// https://www.unicode.org/Public/<version>/ucd/ (the first two and the test
// under auxiliary/ and emoji/). Use the version of the `unicode-segmentation`
// crate the interpreter is built with — its `UNICODE_VERSION`, 17.0.0 on
// 2026-11-23 — not Rust's own, which is newer. A browser's Intl.Segmenter
// follows the ICU it shipped with, which is why there is a table at all.

import { readFileSync, writeFileSync, existsSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, '..', 'src', 'zymbol', 'graphemes.js');
const [ucd, flag] = process.argv.slice(2);
if (!ucd || !existsSync(join(ucd, 'GraphemeBreakProperty.txt'))) {
  console.error('usage: node tools/gen_graphemes.mjs <ucd-dir> [--check|--test]');
  process.exit(2);
}
const read = f => readFileSync(join(ucd, f), 'utf8');
const hex = h => parseInt(h, 16);
const version = /-(\d+\.\d+\.\d+)\.txt/.exec(read('GraphemeBreakProperty.txt').split('\n')[0])?.[1] ?? '?';

// The classes, one letter each in the table. ExtPict and the InCB values are
// separate properties, folded into the same code as the break property: no code
// point has two of them that the rules read at the same time except
// ExtPict + nothing, and InCB=Extend, which is always GBP=Extend or ZWJ — so
// those get their own codes.
const CODES = {
  CR: 'c', LF: 'f', Control: 'o', Extend: 'e', ZWJ: 'z', Regional_Indicator: 'r',
  Prepend: 'p', SpacingMark: 's', L: 'l', V: 'v', T: 't', LV: 'w', LVT: 'x',
};
const cls = new Map();
function ranges(file, want) {
  const out = [];
  for (const l of read(file).split('\n')) {
    const body = l.split('#')[0].trim();
    if (!body) continue;
    const [range, ...props] = body.split(';').map(s => s.trim());
    if (!want(props)) continue;
    const [a, b] = range.split('..').map(hex);
    out.push([a, b ?? a, props]);
  }
  return out;
}
for (const [a, b, [p]] of ranges('GraphemeBreakProperty.txt', () => true)) {
  for (let cp = a; cp <= b; cp++) cls.set(cp, CODES[p]);
}
for (const [a, b] of ranges('emoji-data.txt', p => p[0] === 'Extended_Pictographic')) {
  for (let cp = a; cp <= b; cp++) if (!cls.has(cp)) cls.set(cp, 'g');
}
for (const [a, b, p] of ranges('DerivedCoreProperties.txt', p => p[0] === 'InCB')) {
  for (let cp = a; cp <= b; cp++) {
    const v = p[1];
    const was = cls.get(cp);
    if (v === 'Consonant') cls.set(cp, 'k');                 // GBP=Other
    else if (v === 'Linker') cls.set(cp, 'n');               // GBP=Extend
    else if (v === 'Extend') cls.set(cp, was === 'z' ? 'Z' : 'E');
  }
}
// As runs of one class: `start,length,code`, base 36.
const keys = [...cls.keys()].sort((x, y) => x - y);
const runs = [];
for (let i = 0; i < keys.length;) {
  const s = keys[i], c = cls.get(s);
  let n = 1;
  while (i + n < keys.length && keys[i + n] === s + n && cls.get(keys[i + n]) === c) n++;
  runs.push(`${s.toString(36)},${n.toString(36)},${c}`);
  i += n;
}

const src = `// SPDX-License-Identifier: AGPL-3.0-only
// GENERATED by tools/gen_graphemes.mjs from the Unicode Character Database ${version}
// — do not edit. Regenerate with: node tools/gen_graphemes.mjs <ucd-dir>
//
// Extended grapheme clusters (UAX #29) for both browser engines: \`std/text\`'s
// \`graphemes\` (D-19) and the clusters \`std/term\` measures. The version is
// that of the \`unicode-segmentation\` crate the Rust engines use, and the rules
// pass that version's GraphemeBreakTest.txt (\`--test\` in the generator). A
// browser's Intl.Segmenter follows the ICU it shipped with, so it is not used.

export const UNICODE_VERSION = '${version}';

const RUNS = '${runs.join(' ')}';

let table = null;
function classes() {
  if (table) return table;
  const starts = [], ends = [], codes = [];
  for (const r of RUNS.split(' ')) {
    const [s, n, c] = r.split(',');
    const a = parseInt(s, 36);
    starts.push(a); ends.push(a + parseInt(n, 36) - 1); codes.push(c);
  }
  return (table = { starts, ends, codes });
}
// The class of a code point: one of c f o e z r p s l v t w x (the break
// property), g (Extended_Pictographic), k n E Z (InCB Consonant, Linker, Extend,
// and ZWJ that is InCB=Extend), or '' for Other.
function classOf(cp) {
  const { starts, ends, codes } = classes();
  let lo = 0, hi = starts.length - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    if (cp < starts[mid]) hi = mid - 1; else if (cp > ends[mid]) lo = mid + 1; else return codes[mid];
  }
  return '';
}
const isExtend = c => c === 'e' || c === 'E' || c === 'n' || c === 'z' || c === 'Z';
const isControl = c => c === 'c' || c === 'f' || c === 'o';

/** The extended grapheme clusters of a text, in order. */
export function graphemes(s) {
  const cps = [...s];
  const out = [];
  if (cps.length === 0) return out;
  let cur = cps[0];
  let prev = classOf(cps[0].codePointAt(0));
  let ri = prev === 'r' ? 1 : 0;              // regional indicators in a row
  let pict = prev === 'g' ? 1 : 0;            // 1: ExtPict Extend*, 2: … ZWJ
  let incb = prev === 'k' ? 1 : 0;            // 1: Consonant [Extend|Linker]*, 2: … with a Linker
  for (let i = 1; i < cps.length; i++) {
    const c = classOf(cps[i].codePointAt(0));
    let join;
    if (prev === 'c' && c === 'f') join = true;                       // GB3
    else if (isControl(prev) || isControl(c)) join = false;           // GB4, GB5
    else if (prev === 'l' && (c === 'l' || c === 'v' || c === 'w' || c === 'x')) join = true; // GB6
    else if ((prev === 'w' || prev === 'v') && (c === 'v' || c === 't')) join = true;        // GB7
    else if ((prev === 'x' || prev === 't') && c === 't') join = true;                       // GB8
    else if (isExtend(c) || c === 's') join = true;                   // GB9, GB9a
    else if (prev === 'p') join = true;                               // GB9b
    else if (incb === 2 && c === 'k') join = true;                    // GB9c
    else if (pict === 2 && c === 'g') join = true;                    // GB11
    else if (prev === 'r' && c === 'r' && ri % 2 === 1) join = true;  // GB12, GB13
    else join = false;                                                // GB999
    if (join) cur += cps[i]; else { out.push(cur); cur = cps[i]; }
    // The state the next decision reads.
    ri = c === 'r' ? (join ? ri + 1 : 1) : 0;
    if (c === 'g') pict = 1;
    else if (pict >= 1 && (c === 'e' || c === 'E' || c === 'n')) pict = pict === 1 ? 1 : 0;
    else if (pict === 1 && (c === 'z' || c === 'Z')) pict = 2;
    else pict = 0;
    if (c === 'k') incb = 1;
    else if (incb >= 1 && c === 'n') incb = 2;
    else if (incb >= 1 && (c === 'E' || c === 'Z')) incb = incb;
    else incb = 0;
    prev = c;
  }
  out.push(cur);
  return out;
}
`;

if (flag === '--check') {
  const now = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (now !== src) { console.error(`graphemes.js is not what Unicode ${version} gives: regenerate it`); process.exit(1); }
  console.log(`graphemes.js is current (Unicode ${version})`);
} else if (flag === '--test') {
  const tmp = join(HERE, '..', 'src', 'zymbol', `.graphemes_test_${process.pid}.mjs`);
  writeFileSync(tmp, src);
  const { graphemes } = await import(tmp);
  (await import('fs')).unlinkSync(tmp);
  let ok = 0, bad = 0;
  for (const l of read('GraphemeBreakTest.txt').split('\n')) {
    const body = l.split('#')[0].trim();
    if (!body) continue;
    const want = []; let cur = '';
    for (const tok of body.split(/\s+/)) {
      if (tok === '÷') { if (cur) { want.push(cur); cur = ''; } }
      else if (tok !== '×') cur += String.fromCodePoint(hex(tok));
    }
    const got = graphemes(want.join(''));
    if (JSON.stringify(got) === JSON.stringify(want)) ok++;
    else { bad++; if (bad <= 5) console.log('FAIL', body); }
  }
  console.log(`GraphemeBreakTest ${version}: ${ok} pass, ${bad} fail`);
  process.exit(bad ? 1 : 0);
} else {
  writeFileSync(OUT, src);
  console.log(`wrote ${OUT}: Unicode ${version}, ${src.length} bytes`);
}
