#!/usr/bin/env node
// SPDX-License-Identifier: AGPL-3.0-only
// Generate src/zymbol/normalize.js — the NFC that names are read in (D-20) —
// for the two browser engines, from the Unicode Character Database.
//
//   node tools/gen_normalize.mjs <ucd-dir>           # write src/zymbol/normalize.js
//   node tools/gen_normalize.mjs <ucd-dir> --check   # exit 1 if it is not current
//   node tools/gen_normalize.mjs <ucd-dir> --test    # run NormalizationTest.txt on it
//
// <ucd-dir> holds UnicodeData.txt, DerivedNormalizationProps.txt and
// NormalizationTest.txt of one version, from
// https://www.unicode.org/Public/<version>/ucd/. Use the version of the
// `unicode-normalization` crate the interpreter is built with — its
// `UNICODE_VERSION`, 18.0.0 on 2026-11-23. A browser's String.prototype.normalize
// follows the ICU it shipped with, which is why there is a table at all.
//
// What the table holds: each canonical decomposition of one step (UnicodeData
// field 5 without a <tag>), the canonical combining classes, and the code
// points excluded from composition (Full_Composition_Exclusion). The full
// decompositions and the pairs that compose are derived from those when the
// table is first used. Hangul syllables are arithmetic and have no entries.

import { readFileSync, writeFileSync, existsSync, unlinkSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, '..', 'src', 'zymbol', 'normalize.js');
const [ucd, flag] = process.argv.slice(2);
if (!ucd || !existsSync(join(ucd, 'UnicodeData.txt')) || !existsSync(join(ucd, 'DerivedNormalizationProps.txt'))) {
  console.error('usage: node tools/gen_normalize.mjs <ucd-dir> [--check|--test]');
  process.exit(2);
}
const read = f => readFileSync(join(ucd, f), 'utf8');
const hex = h => parseInt(h, 16);
const version = /-(\d+\.\d+\.\d+)\.txt/.exec(read('DerivedNormalizationProps.txt').split('\n')[0])?.[1] ?? '?';

const decomp = [];            // [cp, [a, b?]]
const ccc = new Map();
for (const l of read('UnicodeData.txt').split('\n')) {
  if (!l) continue;
  const f = l.split(';');
  const cp = hex(f[0]);
  if (f[3] !== '0') ccc.set(cp, Number(f[3]));
  if (f[5] && !f[5].startsWith('<')) decomp.push([cp, f[5].split(' ').map(hex)]);
}
// UnicodeData lists a range's first and last code point only; no range has a
// non-zero class or a decomposition, so nothing is lost.
const fce = [];
for (const l of read('DerivedNormalizationProps.txt').split('\n')) {
  const body = l.split('#')[0].trim();
  if (!body) continue;
  const [range, prop] = body.split(';').map(s => s.trim());
  if (prop !== 'Full_Composition_Exclusion') continue;
  const [a, b] = range.split('..').map(hex);
  fce.push([a, b ?? a]);
}
fce.sort((x, y) => x[0] - y[0]);

const b36 = n => n.toString(36);
const DECOMP = decomp.map(([cp, d]) => `${b36(cp)}:${d.map(b36).join('.')}`).join(' ');
// The classes as runs `start,length,class`.
const keys = [...ccc.keys()].sort((x, y) => x - y);
const runs = [];
for (let i = 0; i < keys.length;) {
  const s = keys[i], c = ccc.get(s);
  let n = 1;
  while (i + n < keys.length && keys[i + n] === s + n && ccc.get(keys[i + n]) === c) n++;
  runs.push(`${b36(s)},${b36(n)},${b36(c)}`);
  i += n;
}
const FCE = fce.map(([a, b]) => `${b36(a)}-${b36(b - a)}`).join(' ');

const src = `// SPDX-License-Identifier: AGPL-3.0-only
// GENERATED by tools/gen_normalize.mjs from the Unicode Character Database ${version}
// — do not edit. Regenerate with: node tools/gen_normalize.mjs <ucd-dir>
//
// NFC, the canonical composition of Unicode, for both browser engines: the form
// a name is read in (D-20), so \`й\` typed as U+0439 and as U+0438 U+0306 is one
// name. The version is that of the \`unicode-normalization\` crate the Rust
// engines use, and the result passes that version's NormalizationTest.txt
// (\`--test\` in the generator). A browser's String.prototype.normalize follows
// the ICU it shipped with, so it is not used.

export const UNICODE_VERSION = '${version}';

const DECOMP = '${DECOMP}';
const CCC = '${runs.join(' ')}';
const FCE = '${FCE}';

const SBASE = 0xAC00, LBASE = 0x1100, VBASE = 0x1161, TBASE = 0x11A7;
const LCOUNT = 19, VCOUNT = 21, TCOUNT = 28, NCOUNT = VCOUNT * TCOUNT, SCOUNT = LCOUNT * NCOUNT;

let tables = null;
function t() {
  if (tables) return tables;
  const one = new Map();
  for (const e of DECOMP.split(' ')) {
    const [k, v] = e.split(':');
    one.set(parseInt(k, 36), v.split('.').map(x => parseInt(x, 36)));
  }
  const ccc = new Map();
  for (const r of CCC.split(' ')) {
    const [s, n, c] = r.split(',').map(x => parseInt(x, 36));
    for (let k = 0; k < n; k++) ccc.set(s + k, c);
  }
  const excluded = new Set();
  for (const r of FCE.split(' ')) {
    const [a, n] = r.split('-').map(x => parseInt(x, 36));
    for (let k = 0; k <= n; k++) excluded.add(a + k);
  }
  const full = new Map();
  const expand = cp => {
    const d = one.get(cp);
    if (!d) return [cp];
    if (!full.has(cp)) full.set(cp, d.flatMap(expand));
    return full.get(cp);
  };
  for (const cp of one.keys()) expand(cp);
  const compose = new Map();
  for (const [cp, d] of one) {
    if (d.length === 2 && !excluded.has(cp)) compose.set(d[0] * 0x110000 + d[1], cp);
  }
  return (tables = { full, ccc, compose });
}

function decompose(cp, out, full) {
  const s = cp - SBASE;
  if (s >= 0 && s < SCOUNT) {
    out.push(LBASE + Math.floor(s / NCOUNT), VBASE + Math.floor((s % NCOUNT) / TCOUNT));
    if (s % TCOUNT) out.push(TBASE + s % TCOUNT);
    return;
  }
  const d = full.get(cp);
  if (d) out.push(...d); else out.push(cp);
}
function composePair(a, b, compose) {
  const l = a - LBASE, v = b - VBASE;
  if (l >= 0 && l < LCOUNT && v >= 0 && v < VCOUNT) return SBASE + (l * VCOUNT + v) * TCOUNT;
  const s = a - SBASE, tt = b - TBASE;
  if (s >= 0 && s < SCOUNT && s % TCOUNT === 0 && tt > 0 && tt < TCOUNT) return a + tt;
  return compose.get(a * 0x110000 + b);
}

/** A text in NFC. Below U+0300 nothing decomposes and nothing combines. */
export function nfc(text) {
  let plain = true;
  for (let i = 0; i < text.length; i++) if (text.charCodeAt(i) >= 0x300) { plain = false; break; }
  if (plain) return text;
  const { full, ccc, compose } = t();
  // Decompose, then put each run of marks in the order of their classes.
  const d = [];
  for (const c of text) decompose(c.codePointAt(0), d, full);
  for (let i = 1; i < d.length; i++) {
    const c = ccc.get(d[i]) ?? 0;
    if (c === 0) continue;
    let j = i;
    while (j > 0 && (ccc.get(d[j - 1]) ?? 0) > c) { [d[j - 1], d[j]] = [d[j], d[j - 1]]; j--; }
  }
  // Compose each character with the last starter, unless something between
  // them blocks it: a starter, or a mark whose class is not lower than its own.
  // \`last\` is the class of what was appended after the starter, -1 for nothing.
  const out = [];
  let starter = -1, last = -1;
  for (const cp of d) {
    const c = ccc.get(cp) ?? 0;
    if (starter >= 0 && (last === -1 || (last !== 0 && last < c))) {
      const p = composePair(out[starter], cp, compose);
      if (p !== undefined) { out[starter] = p; continue; }
    }
    if (c === 0) { starter = out.length; last = -1; } else last = c;
    out.push(cp);
  }
  return String.fromCodePoint(...out);
}
`;

if (flag === '--check') {
  const now = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (now !== src) { console.error(`normalize.js is not what Unicode ${version} gives: regenerate it`); process.exit(1); }
  console.log(`normalize.js is current (Unicode ${version})`);
} else if (flag === '--test') {
  const tmp = join(HERE, '..', 'src', 'zymbol', `.normalize_test_${process.pid}.mjs`);
  writeFileSync(tmp, src);
  const { nfc } = await import(tmp);
  unlinkSync(tmp);
  const str = f => String.fromCodePoint(...f.trim().split(' ').map(hex));
  let ok = 0, bad = 0;
  const listed = new Set();
  let part = '';
  for (const l of read('NormalizationTest.txt').split('\n')) {
    if (l.startsWith('@Part')) { part = l.split(' ')[0].trim(); continue; }
    const body = l.split('#')[0].trim();
    if (!body) continue;
    const [c1, c2, c3, c4, c5] = body.split(';').slice(0, 5).map(str);
    if (part === '@Part1') listed.add(c1.codePointAt(0));
    // NFC conformance: c2 == NFC(c1) == NFC(c2) == NFC(c3), c4 == NFC(c4) == NFC(c5).
    const pass = nfc(c1) === c2 && nfc(c2) === c2 && nfc(c3) === c2 && nfc(c4) === c4 && nfc(c5) === c4;
    if (pass) ok++; else { bad++; if (bad <= 5) console.log('FAIL', body); }
  }
  // Every code point Part 1 does not list is its own NFC.
  let others = 0;
  for (let cp = 0; cp <= 0x10FFFF; cp++) {
    if ((cp >= 0xD800 && cp <= 0xDFFF) || listed.has(cp)) continue;
    const c = String.fromCodePoint(cp);
    if (nfc(c) !== c) { bad++; if (bad <= 5) console.log('FAIL unlisted', cp.toString(16)); } else others++;
  }
  console.log(`NormalizationTest ${version}: ${ok} lines pass, ${others} unlisted code points unchanged, ${bad} fail`);
  process.exit(bad ? 1 : 0);
} else {
  writeFileSync(OUT, src);
  console.log(`wrote ${OUT}: Unicode ${version}, ${src.length} bytes`);
}
