#!/usr/bin/env node
// SPDX-License-Identifier: AGPL-3.0-only
// Generate src/zymbol/skeleton.js — the confusable skeleton of UTS #39, which
// the editor uses to say that two names look the same (D-21) — for the
// playground, from Unicode's data files.
//
//   node tools/gen_skeleton.mjs <confusables.txt> <DerivedCoreProperties.txt>           # write
//   node tools/gen_skeleton.mjs <confusables.txt> <DerivedCoreProperties.txt> --check   # exit 1 if stale
//
// confusables.txt is https://www.unicode.org/Public/security/<version>/confusables.txt
// and DerivedCoreProperties.txt is https://www.unicode.org/Public/<version>/ucd/,
// of the version of the `unicode-security` crate the language server is built
// with — its `UNICODE_VERSION`, 18.0.0 on 2026-11-24.
//
// The skeleton is the crate's: NFD, drop the Default_Ignorable code points,
// replace each code point by its prototype, NFD again. The NFD is normalize.js's,
// generated from the same version.

import { readFileSync, writeFileSync, existsSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, '..', 'src', 'zymbol', 'skeleton.js');
const [conf, dcp, flag] = process.argv.slice(2);
if (!conf || !dcp || !existsSync(conf) || !existsSync(dcp)) {
  console.error('usage: node tools/gen_skeleton.mjs <confusables.txt> <DerivedCoreProperties.txt> [--check]');
  process.exit(2);
}
const hex = h => parseInt(h, 16);
const confText = readFileSync(conf, 'utf8').replace(/^﻿/, '');
const version = /# Version: (\d+\.\d+\.\d+)/.exec(confText)?.[1] ?? '?';
const dcpVersion = /-(\d+\.\d+\.\d+)\.txt/.exec(readFileSync(dcp, 'utf8').split('\n')[0])?.[1] ?? '?';
if (version !== dcpVersion) {
  console.error(`confusables.txt is ${version} and DerivedCoreProperties.txt is ${dcpVersion}: use one version`);
  process.exit(2);
}

const proto = new Map();
for (const l of confText.split('\n')) {
  const body = l.split('#')[0].trim();
  if (!body) continue;
  const [src, target] = body.split(';').map(s => s.trim());
  proto.set(hex(src), target.split(/\s+/).map(hex));
}
// One-to-one mappings as runs `start,count,delta` in base 36 — the mathematical
// alphabets map letter after letter onto A–Z — and the rest as `cp:a.b.c`.
const singles = [...proto].filter(([, v]) => v.length === 1).map(([k, v]) => [k, v[0]]).sort((a, b) => a[0] - b[0]);
const runs = [];
for (let i = 0; i < singles.length;) {
  const [s, t] = singles[i];
  let n = 1;
  while (i + n < singles.length && singles[i + n][0] === s + n && singles[i + n][1] === t + n) n++;
  runs.push([s, n, t - s].map(x => x.toString(36)).join(','));
  i += n;
}
const multi = [...proto].filter(([, v]) => v.length > 1).sort((a, b) => a[0] - b[0])
  .map(([k, v]) => `${k.toString(36)}:${v.map(x => x.toString(36)).join('.')}`);

const ignorable = [];
for (const l of readFileSync(dcp, 'utf8').split('\n')) {
  const body = l.split('#')[0].trim();
  if (!body) continue;
  const [range, prop] = body.split(';').map(s => s.trim());
  if (prop !== 'Default_Ignorable_Code_Point') continue;
  const [a, b] = range.split('..').map(hex);
  ignorable.push([a, b ?? a]);
}
ignorable.sort((x, y) => x[0] - y[0]);

const src = `// SPDX-License-Identifier: AGPL-3.0-only
// GENERATED by tools/gen_skeleton.mjs from Unicode's confusables.txt ${version}
// — do not edit. Regenerate with: node tools/gen_skeleton.mjs <confusables.txt> <DerivedCoreProperties.txt>
//
// The confusable skeleton of UTS #39: two names whose skeletons are equal look
// the same. The playground's problems panel says so (D-21), as the language
// server does with the \`unicode-security\` crate, whose data is this version.

import { nfd } from './normalize.js';

export const UNICODE_VERSION = '${version}';

const RUNS = '${runs.join(' ')}';
const MULTI = '${multi.join(' ')}';
const IGNORABLE = '${ignorable.map(([a, b]) => `${a.toString(36)}-${(b - a).toString(36)}`).join(' ')}';

let tables = null;
function t() {
  if (tables) return tables;
  const proto = new Map();
  for (const r of RUNS.split(' ')) {
    const [s, n, d] = r.split(',').map(x => parseInt(x, 36));
    for (let k = 0; k < n; k++) proto.set(s + k, String.fromCodePoint(s + k + d));
  }
  for (const e of MULTI.split(' ')) {
    const [k, v] = e.split(':');
    proto.set(parseInt(k, 36), String.fromCodePoint(...v.split('.').map(x => parseInt(x, 36))));
  }
  const ignorable = IGNORABLE.split(' ').map(r => { const [a, n] = r.split('-').map(x => parseInt(x, 36)); return [a, a + n]; });
  return (tables = { proto, ignorable });
}
function isIgnorable(cp, ranges) {
  let lo = 0, hi = ranges.length - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    if (cp < ranges[mid][0]) hi = mid - 1; else if (cp > ranges[mid][1]) lo = mid + 1; else return true;
  }
  return false;
}

/** The skeleton of a text: NFD, no default-ignorable code points, each code point its prototype, NFD. */
export function skeleton(text) {
  const { proto, ignorable } = t();
  let out = '';
  for (const c of nfd(text)) {
    const cp = c.codePointAt(0);
    if (isIgnorable(cp, ignorable)) continue;
    out += proto.get(cp) ?? c;
  }
  return nfd(out);
}
`;

if (flag === '--check') {
  const now = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (now !== src) { console.error(`skeleton.js is not what confusables ${version} gives: regenerate it`); process.exit(1); }
  console.log(`skeleton.js is current (confusables ${version})`);
} else {
  writeFileSync(OUT, src);
  console.log(`wrote ${OUT}: confusables ${version}, ${src.length} bytes`);
}
