#!/usr/bin/env node
// SPDX-License-Identifier: AGPL-3.0-only
// Generate src/zymbol/vm/isa.js from Rust's `Instruction` enum.
//
//   node tools/gen_isa.mjs           write the table
//   node tools/gen_isa.mjs --check   exit 1 if the written table is not what Rust says
//
// The table is never written by hand. An opcode is the position of its variant
// in `interpreter/crates/zymbol-bytecode/src/lib.rs`, which is also the index
// bincode writes for it — the number a .zyb file would carry — so the two VMs
// agree on what instruction 17 is only while this check passes. Inserting a
// variant in Rust renumbers every one after it; `--check` is what notices.
//
// The interpreter checkout is the one beside this repository's, or
// $ZYMBOL_INTERPRETER.

import { readFileSync, writeFileSync } from 'fs';
import { createHash } from 'crypto';
import { dirname, join, resolve } from 'path';
import { fileURLToPath } from 'url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..');
const INTERPRETER = process.env.ZYMBOL_INTERPRETER ?? resolve(ROOT, '../../interpreter');
const SOURCE = join(INTERPRETER, 'crates/zymbol-bytecode/src/lib.rs');
const TARGET = join(ROOT, '../src/zymbol/vm/isa.js');

// The body of `pub enum Instruction { … }`, comments stripped.
function enumBody(text) {
  const start = text.indexOf('pub enum Instruction {');
  if (start < 0) throw new Error(`no \`pub enum Instruction\` in ${SOURCE}`);
  let depth = 0, i = text.indexOf('{', start);
  const open = i;
  for (; i < text.length; i++) {
    if (text[i] === '{') depth++;
    else if (text[i] === '}' && --depth === 0) break;
  }
  return text.slice(open + 1, i).split('\n').map(l => l.replace(/\/\/.*$/, '')).join('\n');
}

// Split on commas at depth 0 of (), <> and {}.
function splitTop(s) {
  const out = []; let depth = 0, cur = '';
  for (const ch of s) {
    if ('(<{'.includes(ch)) depth++;
    if (')>}'.includes(ch)) depth--;
    if (ch === ',' && depth === 0) { out.push(cur.trim()); cur = ''; continue; }
    cur += ch;
  }
  if (cur.trim()) out.push(cur.trim());
  return out;
}

function variants(body) {
  const items = splitTop(body.replace(/#\[[^\]]*\]/g, ''));
  return items.map(item => {
    const m = item.match(/^([A-Z][A-Za-z0-9]*)\s*(?:\((.*)\))?$/s);
    if (!m) throw new Error(`cannot read variant: ${item}`);
    const operands = m[2] ? splitTop(m[2]).map(t => t.replace(/\s+/g, ' ')) : [];
    return [m[1], operands];
  });
}

const rust = readFileSync(SOURCE, 'utf8');
const ops = variants(enumBody(rust));
const canonical = ops.map(([n, t]) => `${n}(${t.join(',')})`).join(';');
const fingerprint = createHash('sha256').update(canonical).digest('hex').slice(0, 16);

const lines = [
  '// SPDX-License-Identifier: AGPL-3.0-only',
  '// GENERATED by tools/gen_isa.mjs from interpreter/crates/zymbol-bytecode/src/lib.rs.',
  '// Do not edit: run `node tools/gen_isa.mjs`, and `--check` to verify it.',
  '//',
  '// An opcode is the position of its variant in Rust\'s `Instruction` enum, which',
  '// is also the variant index bincode writes for it.',
  '',
  `export const ISA_FINGERPRINT = '${fingerprint}';`,
  `export const ISA_SIZE = ${ops.length};`,
  '',
  '// [name, operand types], in declaration order.',
  'export const OPS = [',
  ...ops.map(([n, t], i) => `  [${JSON.stringify(n)}, ${JSON.stringify(t)}], // ${i}`),
  '];',
  '',
  'export const OP = Object.freeze(Object.fromEntries(OPS.map(([n], i) => [n, i])));',
  '',
];
const generated = lines.join('\n');

// The machine's dispatch switch writes each opcode as a literal, `case 17: // NegInt`,
// so V8 builds a jump table. Every such label must still be the opcode Rust gives
// that name, and the labels must be exactly the IMPLEMENTED set.
function checkMachine() {
  const text = readFileSync(join(ROOT, '../src/zymbol/vm/machine.js'), 'utf8');
  const start = text.indexOf('switch (ins.op) {');
  // The dispatch's own default, not the first `default:` of a switch nested in a case.
  const end = text.indexOf('throw new NotYet(`instruction', start);
  const problems = [];
  const labelled = new Set();
  for (const line of text.slice(start, end).split('\n')) {
    const nums = [...line.matchAll(/case (\d+):/g)].map(m => Number(m[1]));
    if (nums.length === 0) continue;
    const comment = line.match(/\/\/\s*(.*)$/);
    const names = comment ? comment[1].match(/[A-Z][A-Za-z]*/g) ?? [] : [];
    nums.forEach((n, i) => {
      const rust = ops[n]?.[0];
      if (names[i] !== rust) problems.push(`case ${n} says ${names[i] ?? '(nothing)'}, Rust's opcode ${n} is ${rust}`);
      labelled.add(rust);
    });
  }
  const implemented = new Set([...text.matchAll(/IMPLEMENTED = new Set\(\[([\s\S]*?)\]\)/g)][0][1].match(/'([A-Za-z]+)'/g).map(s => s.slice(1, -1)));
  for (const n of labelled) if (!implemented.has(n)) problems.push(`${n} has a case but is not in IMPLEMENTED`);
  for (const n of implemented) if (!labelled.has(n)) problems.push(`${n} is in IMPLEMENTED but has no case`);
  return { problems, count: labelled.size };
}

if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(TARGET, 'utf8'); } catch { /* missing reads as stale */ }
  if (current !== generated) {
    console.error(`isa.js is stale: Rust's Instruction enum has ${ops.length} variants, fingerprint ${fingerprint}.`);
    console.error('Run `node tools/gen_isa.mjs`, then bring the VM up to the instructions that changed.');
    process.exit(1);
  }
  const { problems, count } = checkMachine();
  if (problems.length) {
    console.error(`machine.js disagrees with Rust's opcodes:\n  ${problems.join('\n  ')}`);
    process.exit(1);
  }
  console.log(`isa.js matches Rust: ${ops.length} instructions, fingerprint ${fingerprint}; machine.js implements ${count}, every label correct`);
} else {
  writeFileSync(TARGET, generated);
  console.log(`wrote ${TARGET}: ${ops.length} instructions, fingerprint ${fingerprint}`);
}
